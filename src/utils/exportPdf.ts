import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { formatDate, formatMoney } from './format';
import type { MaintenanceRecord, Vehicle } from '../types';

// Stops text typed by the user (such as notes) from breaking the page layout
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildHtml(vehicle: Vehicle, records: MaintenanceRecord[]): string {
  const total = records.reduce((sum, r) => sum + (r.cost || 0), 0);
  const generated = formatDate(Date.now());
  const type = vehicle.vehicleType === 'motorbike' ? 'Motorbike' : 'Car';

  const rows = records
    .map(
      (r) => `
      <tr>
        <td>${formatDate(r.date)}</td>
        <td>${escapeHtml(r.serviceType)}</td>
        <td class="num">${r.odometer.toLocaleString()}</td>
        <td class="num">${r.cost > 0 ? escapeHtml(formatMoney(r.cost)) : '-'}</td>
        <td>${escapeHtml(r.notes || '-')}</td>
      </tr>`
    )
    .join('');

  return `
<html>
  <head>
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no" />
    <style>
      body { font-family: -apple-system, Helvetica, Arial, sans-serif; color: #1E1B2E; padding: 24px; }
      .brand { color: #5E4B9E; font-size: 13px; font-weight: 700; letter-spacing: 1px; }
      h1 { margin: 6px 0 2px; font-size: 24px; }
      .sub { color: #6B6880; font-size: 13px; margin-bottom: 18px; }
      .cards { display: flex; gap: 12px; margin-bottom: 20px; }
      .card { flex: 1; background: #EFEBFA; border-radius: 10px; padding: 12px 14px; }
      .card .label { color: #6B6880; font-size: 11px; }
      .card .value { color: #5E4B9E; font-size: 18px; font-weight: 700; margin-top: 4px; }
      table { width: 100%; border-collapse: collapse; font-size: 12px; }
      th { background: #5E4B9E; color: #FFFFFF; text-align: left; padding: 8px; }
      td { padding: 8px; border-bottom: 1px solid #E4E1EE; vertical-align: top; }
      tr:nth-child(even) td { background: #F7F6FB; }
      .num { text-align: right; white-space: nowrap; }
      .footer { margin-top: 20px; color: #6B6880; font-size: 11px; }
    </style>
  </head>
  <body>
    <div class="brand">SERVICEMATE</div>
    <h1>${escapeHtml(vehicle.make)} ${escapeHtml(vehicle.model)}</h1>
    <div class="sub">
      ${vehicle.year} &bull; ${escapeHtml(vehicle.licensePlate)} &bull; ${type} &bull;
      ${vehicle.odometer.toLocaleString()} km
    </div>

    <div class="cards">
      <div class="card">
        <div class="label">Total spend</div>
        <div class="value">${escapeHtml(formatMoney(total))}</div>
      </div>
      <div class="card">
        <div class="label">Services logged</div>
        <div class="value">${records.length}</div>
      </div>
    </div>

    <table>
      <thead>
        <tr>
          <th>Date</th>
          <th>Service</th>
          <th class="num">Odometer (km)</th>
          <th class="num">Cost</th>
          <th>Notes</th>
        </tr>
      </thead>
      <tbody>${rows}</tbody>
    </table>

    <div class="footer">Maintenance history generated by ServiceMate on ${generated}.</div>
  </body>
</html>`;
}

// Creates the PDF and opens the phone's share sheet (save to Files, email, WhatsApp...)
export async function exportMaintenancePdf(vehicle: Vehicle, records: MaintenanceRecord[]) {
  const html = buildHtml(vehicle, records);
  const { uri } = await Print.printToFileAsync({ html });

  if (!(await Sharing.isAvailableAsync())) {
    throw new Error('Sharing is not available on this device');
  }

  await Sharing.shareAsync(uri, {
    mimeType: 'application/pdf',
    UTI: '.pdf',
    dialogTitle: `${vehicle.make} ${vehicle.model} maintenance history`,
  });
}